import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Browser Exam Mode reads the same reviewed question literals as the Academy
// Hub mobile trainer.  We intentionally export only answerable German banks.
const here = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(here, '..');
const sourcePath = path.resolve(webRoot, '..', 'vela academy hub', 'features', 'native-flow', 'native-practice-exam-mode-screen.tsx');
const source = fs.readFileSync(sourcePath, 'utf8');

function balanced(sourceText, start) {
  let depth = 0; let quote = ''; let escaped = false;
  for (let index = start; index < sourceText.length; index += 1) {
    const char = sourceText[index];
    if (quote) {
      if (escaped) escaped = false;
      else if (char === '\\') escaped = true;
      else if (char === quote) quote = '';
      continue;
    }
    if (char === "'" || char === '"' || char === '`') { quote = char; continue; }
    if (char === '[') depth += 1;
    if (char === ']') { depth -= 1; if (depth === 0) return sourceText.slice(start, index + 1); }
  }
  throw new Error('Unclosed question array');
}

function questionsFor(board) {
  const marker = `  ${board}: [`;
  const markerAt = source.indexOf(marker, source.indexOf('const examQuestions:'));
  if (markerAt < 0) throw new Error(`Missing ${board} mobile exam bank`);
  const literal = balanced(source, source.indexOf('[', markerAt));
  return Function(`"use strict"; return (${literal});`)()
    .filter((item) => item && item.answer && Array.isArray(item.options) && item.options.includes(item.answer))
    .map((item) => ({ ...item, board }));
}

const boards = ['goethe', 'telc', 'dtz', 'testdaf'];
const questions = boards.flatMap(questionsFor);
if (!questions.length || questions.some((item) => !item.id || !item.prompt)) throw new Error('Invalid mobile exam question bank');

const payload = {
  source: 'Duvela Academy Hub Native Exam Mode',
  sourceHash: crypto.createHash('sha256').update(source).digest('hex'),
  syncedAt: new Date().toISOString(),
  questions,
};
const target = path.join(webRoot, 'web', 'content', 'mobile-exam-bank.js');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, `/* Generated by scripts/sync-mobile-exam-bank.mjs. Do not edit manually. */\nwindow.DuvelaMobileExamBank = Object.freeze(${JSON.stringify(payload)});\n`, 'utf8');
console.log(`Synced ${questions.length} answerable Exam Mode tasks from Academy Hub Mobile.`);
