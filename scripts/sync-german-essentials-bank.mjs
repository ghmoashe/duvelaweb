import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Keep the web trainer on the same reviewed source as Academy Hub.  This script
// deliberately evaluates only the exported task literals; it never invents a
// task, an answer or an explanation on the web side.
const here = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(here, '..');
const hubRoot = path.resolve(webRoot, '..', 'vela academy hub');
const corePath = path.join(hubRoot, 'shared', 'german-essentials-data.ts');
const supplementalPath = path.join(hubRoot, 'shared', 'german-essentials-supplemental-data.ts');
const core = fs.readFileSync(corePath, 'utf8');
const supplemental = fs.readFileSync(supplementalPath, 'utf8');

function balanced(source, marker, open, close) {
  const markerAt = source.indexOf(marker);
  if (markerAt < 0) throw new Error(`Missing ${marker}`);
  const start = source.indexOf(open, markerAt + marker.length);
  if (start < 0) throw new Error(`Missing ${open} after ${marker}`);
  let depth = 0; let quote = ''; let escaped = false;
  for (let index = start; index < source.length; index += 1) {
    const char = source[index];
    if (quote) {
      if (escaped) escaped = false;
      else if (char === '\\') escaped = true;
      else if (char === quote) quote = '';
      continue;
    }
    if (char === "'" || char === '"' || char === '`') { quote = char; continue; }
    if (char === open) depth += 1;
    if (char === close) {
      depth -= 1;
      if (depth === 0) return source.slice(start, index + 1);
    }
  }
  throw new Error(`Unclosed ${marker}`);
}

function evaluate(literal, label) {
  try { return Function(`"use strict"; return (${literal});`)(); }
  catch (error) { throw new Error(`Could not parse ${label}: ${error.message}`); }
}

const coreTasks = evaluate(balanced(core, 'const tasks: GermanEssentialTask[] =', '[', ']'), 'core German essentials');
const supplementalLiteral = balanced(supplemental, 'export const supplementalGermanEssentialTasks: GermanEssentialTask[] =', '[', ']');
const supplementalTasks = Function('task', `"use strict"; return (${supplementalLiteral});`)(function task(input) {
  return { mode: 'choice', ...input };
});
const tasks = [...coreTasks, ...supplementalTasks].map((task) => ({ ...task, mode: task.mode || 'choice' }));
const invalid = tasks.filter((task) => !task.id || !task.answer || !Array.isArray(task.options) || !task.options.includes(task.answer));
if (invalid.length) throw new Error(`Invalid German essentials task(s): ${invalid.map((task) => task.id || '?').join(', ')}`);

const bank = {
  source: 'Duvela Academy Hub Deutsch Trainer',
  sourceHash: crypto.createHash('sha256').update(core).update(supplemental).digest('hex'),
  syncedAt: new Date().toISOString(),
  skills: ['wordOrder', 'cases', 'verbBracket', 'prepositions', 'adjectiveEndings', 'nounGender', 'verbForms', 'pronunciation', 'conversation', 'schreiben'],
  tasks,
};
const target = path.join(webRoot, 'web', 'content', 'german-essentials-bank.js');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, `/* Generated by scripts/sync-german-essentials-bank.mjs. Do not edit manually. */\nwindow.DuvelaGermanEssentialsBank = Object.freeze(${JSON.stringify(bank)});\n`, 'utf8');
console.log(`Synced ${tasks.length} Deutsch Trainer tasks from Duvela Academy Hub.`);
