import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const webRoot = process.cwd();
const mobileRoot = path.resolve(webRoot, '..', 'vela academy hub');
const sourcePath = path.join(mobileRoot, 'shared', 'practice-article-exercises-data.ts');
const outPath = path.join(webRoot, 'web', 'content', 'mobile-article-bank.js');
const source = fs.readFileSync(sourcePath, 'utf8');
const match = source.match(/PRACTICE_ARTICLE_EXERCISE_SEEDS\s*=\s*\[([\s\S]*?)\n\]\s*as const;/);
if (!match) throw new Error('Could not locate mobile article exercise seeds.');
const rows = [...match[1].matchAll(/^\s*\[(.+?)\],?\s*$/gm)].map((item) => JSON.parse('[' + item[1] + ']'));
const exercises = rows.map(([noun, article, hint, level], index) => ({ id:'mobile-article-' + (index + 1), noun, article, hint, level }));
if (!exercises.length || exercises.some((item) => !['der','die','das'].includes(item.article))) throw new Error('Invalid mobile article bank.');
const payload = { source:'Duvela Academy Hub Mobile Guess the Article', sourceHash:crypto.createHash('sha256').update(source).digest('hex'), exercises };
fs.writeFileSync(outPath, '/* Generated by scripts/sync-mobile-article-bank.mjs. */\nwindow.DuvelaMobileArticleBank = Object.freeze(' + JSON.stringify(payload) + ');\n');
console.log(`[article-bank] ${exercises.length} exercises from mobile source`);