// Copies NOVA's sound map (sounds per CEFR level per learning language, with the
// checked minimal pairs) from the Hub app into the web app.
//   source: vela academy hub/shared/nova-sounds.ts
//   output: web/content/nova-sounds.js  (window.DUVELA_NOVA_SOUNDS)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const webRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.resolve(webRoot, '..', 'vela academy hub', 'shared', 'nova-sounds.ts');
const output = path.join(webRoot, 'web', 'content', 'nova-sounds.js');

const text = fs.readFileSync(source, 'utf8').replace(/\r\n/g, '\n');
const banksLine = text.match(/const BANKS: Record<string, Bank> = \{([^}]+)\};/);
if (!banksLine) throw new Error('BANKS map not found in ' + source);

const result = {};
for (const pair of banksLine[1].split(',')) {
  const [key, name] = pair.split(':').map((part) => part.trim());
  if (!key || !name) continue;
  const block = text.match(new RegExp(`const ${name}: Bank = (\\{[\\s\\S]*?\\n\\});`));
  if (!block) throw new Error(`Bank ${name} not found`);
  // The bank is a plain object of string tuples: evaluate it as JavaScript.
  const bank = new Function(`return (${block[1]});`)();
  result[key] = {};
  for (const [level, rows] of Object.entries(bank)) {
    result[key][level] = rows.map(([id, title, en, ru, pairs]) => ({ id, title, en, ru, pairs: pairs || '' }));
  }
}

const count = Object.values(result).reduce((sum, bank) => sum + Object.values(bank).reduce((n, rows) => n + rows.length, 0), 0);
fs.writeFileSync(
  output,
  '// Generated by scripts/sync-nova-sounds.mjs from the Hub app — do not edit by hand.\n' +
    'window.DUVELA_NOVA_SOUNDS = ' + JSON.stringify(result) + ';\n',
);
console.log(`nova sounds: ${Object.keys(result).join(', ')} — ${count} sounds → ${path.relative(webRoot, output)}`);
